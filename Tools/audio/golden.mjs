// Golden values for the kart audio maths, computed by the shipped web code itself.
//
//   node --experimental-transform-types --no-warnings Tools/audio/golden.mjs [<movecade-v2 root>]
//
// It imports drivetrain.ts, soundMix.ts and engineVoice.ts straight from the (read-only) movecade-v2
// checkout, runs fixed scenarios, and writes Source/MovecadeKart/Private/Audio/Tests/KartAudioGolden.inl,
// which the MovecadeKart.Audio.* automation tests compare the C++ port against. EngineVoice runs on a
// mock AudioContext that records each setTargetAtTime target, so the engine-layer numbers come from the
// real update() and not from a copy of its formulas.
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(process.argv[2] ?? 'C:/Users/Jimmy/Documents/Projects/movecade/movecade-v2');
const load = rel => import(pathToFileURL(join(root, rel)).href);
const { createDrivetrain } = await load('app/src/games/kart/drivetrain.ts');
const mix = await load('app/src/games/kart/soundMix.ts');
const { EngineVoice } = await load('app/src/audio/engineVoice.ts');

const DT = 1 / 60;
const num = v => {
  if (!Number.isFinite(v)) throw new Error(`non-finite ${v}`);
  return Number.isInteger(v) ? `${v}.0` : v.toPrecision(17);
};
const lines = [];
const out = s => lines.push(s);

// ── Drivetrain scenarios. Accelerating: -1 = not reported (keyboard), 0 = false, 1 = true. ──
const damp = (speed, target, lambda) => target + (speed - target) * Math.exp(-lambda * DT);
const scenarios = [
  {
    name: 'PhoneRunAndLift', seed: 1, frames: 60 * 12, make() {
      let speed = 0;
      return i => {
        speed = i < 60 * 8 ? damp(speed, 40, 1.8) : damp(speed, 0, 1.1);
        return { speed, accelerating: i < 60 * 8 ? 1 : 0, neutral: false };
      };
    },
  },
  {
    name: 'KeyboardInferred', seed: 7, frames: 60 * 12, make() {
      let speed = 0;
      return i => {
        speed = i < 60 * 8 ? damp(speed, 40, 1.8) : damp(speed, 0, 1.1);
        return { speed, accelerating: -1, neutral: false };
      };
    },
  },
  {
    name: 'GridRev', seed: 2, frames: 60 * 3, make() {
      return i => ({ speed: 0, accelerating: i < 90 ? 1 : 0, neutral: true });
    },
  },
  {
    name: 'BoostKickdown', seed: 3, frames: 60 * 7, make() {
      let speed = 0;
      return i => {
        speed = damp(speed, i < 60 * 3 ? 80 : 40, 1.8);
        return { speed, accelerating: 1, neutral: false };
      };
    },
  },
  {
    name: 'ReverseAndBrake', seed: 4, frames: 60 * 4, make() {
      let speed = 0;
      return i => {
        speed = i < 120 ? damp(speed, -15, 6) : damp(speed, 30, 1.8);
        return { speed, accelerating: i < 120 ? 0 : 1, neutral: false };
      };
    },
  },
];

out('// Generated by Tools/audio/golden.mjs from movecade-v2 drivetrain.ts, soundMix.ts and engineVoice.ts. Do not edit.');
out('// Drivetrain frames: { Speed, Accelerating, bNeutral, Rpm, Gear, Load, bThrottle, bLimiter, EventBits(1 up, 2 down, 4 backfire) }');
for (const s of scenarios) {
  const dt = createDrivetrain(s.seed);
  const next = s.make();
  out(`static const FGoldenDrivetrainFrame Golden${s.name}[] = {`);
  for (let i = 0; i < s.frames; i += 1) {
    const input = next(i);
    const frame = dt.step({
      speed: input.speed, dt: DT, neutral: input.neutral,
      accelerating: input.accelerating < 0 ? undefined : input.accelerating === 1,
    });
    const bits = (frame.events.includes('upshift') ? 1 : 0) | (frame.events.includes('downshift') ? 2 : 0) |
      (frame.events.includes('backfire') ? 4 : 0);
    out(`\t{ ${num(input.speed)}, ${input.accelerating}, ${input.neutral}, ${num(frame.rpm)}, ${frame.gear}, ${num(frame.load)}, ${frame.throttle}, ${frame.limiter}, ${bits} },`);
  }
  out('};');
  out(`static constexpr int32 Golden${s.name}Seed = ${s.seed};`);
}

// ── EngineVoice.update targets on a mock context. ──
const param = value => ({ value, target: undefined, setValueAtTime(v) { this.value = v; }, setTargetAtTime(v) { this.target = v; } });
const node = extra => ({ connect(n) { return n; }, disconnect() {}, ...extra });
const ctx = {
  currentTime: 0,
  createGain: () => node({ gain: param(1) }),
  createStereoPanner: () => node({ pan: param(0) }),
  createBufferSource: () => node({ buffer: null, loop: false, playbackRate: param(1), start() {}, stop() {} }),
};
const buffer = { duration: 4 };
const bank = {
  on: [1000, 2500, 4000, 5500, 7000].map(rpm => ({ rpm, buffer })),
  off: [2500, 6500].map(rpm => ({ rpm, buffer })),
};
const voice = new EngineVoice(ctx, node({}), bank, 0);
out('// Engine voice targets: { Rpm, Load, MixGain, OnBus, OffBus, Out, OnGain[5], OffGain[2], OnRate[5], OffRate[2] }');
out('static const FGoldenEngineMix GoldenEngineMix[] = {');
const rpms = [0, 400, 500, 950, 1000, 1200, 1500, 1800, 2000, 2500, 3100, 4000, 4750, 5500, 6000, 6500, 7000, 7600, 8600, 9500, 12000];
const loads = [-1.5, -1, -0.6, -0.35, -0.3, 0, 0.1, 0.45, 0.6, 1, 1.4];
for (const rpm of rpms) for (const load of loads) {
  const gain = 0.3 * (rpm % 3 === 0 ? 1 : 0.5);
  voice.update({ rpm, load }, { gain, pan: 0 });
  const v = voice;
  const t = layers => layers.map(l => num(l.gain.gain.target));
  const r = layers => layers.map(l => num(l.source.playbackRate.target));
  out(`\t{ ${num(rpm)}, ${num(load)}, ${num(gain)}, ${num(v.onBus.gain.target)}, ${num(v.offBus.gain.target)}, ${num(v.out.gain.target)}, ` +
    `{ ${t(v.on).join(', ')} }, { ${t(v.off).join(', ')} }, { ${r(v.on).join(', ')} }, { ${r(v.off).join(', ')} } },`);
}
out('};');

// ── soundMix.ts ──
out('// windMix: { SpeedMph, Gain, Rate, Lowpass }');
out('static const double GoldenWind[][4] = {');
for (const v of [-50, -3, 0, 3, 4, 5, 10, 20, 30, 40, 55, 60, 79, 80, 120]) {
  const w = mix.windMix(v);
  out(`\t{ ${num(v)}, ${num(w.gain)}, ${num(w.rate)}, ${num(w.lowpass)} },`);
}
out('};');
out('// squealMix: { SpeedMph, bDrifting, DriftPower, Steer, Gain, Rate }');
out('static const double GoldenSqueal[][6] = {');
for (const speed of [0, 5, 6, 12, 20, 28, 30, 40, 48, 60, -35]) for (const drifting of [false, true])
  for (const dp of [0, 0.5, 3, 6, 9]) for (const steer of [0, 0.3, 0.55, 0.8, -1, 1.4]) {
    const s = mix.squealMix({ speedMph: speed, drifting, driftPower: dp, steer });
    out(`\t{ ${num(speed)}, ${drifting ? 1 : 0}.0, ${num(dp)}, ${num(steer)}, ${num(s.gain)}, ${num(s.rate)} },`);
  }
out('};');
out('// impactStrength + impactCue: { SpeedMph, Penetration, bCritical, Strength, Tier(0 light,1 medium,2 heavy), Gain }');
out('static const double GoldenImpact[][6] = {');
const tiers = { light: 0, medium: 1, heavy: 2 };
for (const speed of [0, 5, 12, 20.9, 21, 25, 30, 41.9, 42, 50, 60, 90, -30]) for (const pen of [0, 0.05, 0.2, 0.7])
  for (const critical of [false, true]) {
    const strength = mix.impactStrength({ speedMph: speed, penetration: pen, critical });
    const cue = mix.impactCue(strength);
    out(`\t{ ${num(speed)}, ${num(pen)}, ${critical ? 1 : 0}.0, ${num(strength)}, ${tiers[cue.tier]}.0, ${num(cue.gain)} },`);
  }
out('};');
out('// driftBoostCue: { ActiveBoost, ChargeBeforeRelease, Level (0 = not a drift boost), Gain }');
out('static const FGoldenDriftBoost GoldenDriftBoost[] = {');
for (const label of ['DRIFT_MINI', 'DRIFT_SUPER', 'DRIFT_ULTRA', 'DRIFT_CLEAN_SUPER', 'DRIFT_CLEAN_ULTRA', 'DRIFT_SLOPPY_MINI',
  'DRIFT_SLOPPY_SUPER', 'DRIFT_APEX_ULTRA', 'DRIFT_', 'DRIFT_WEIRD', 'BOOST_PAD', 'START_BOOST', '']) for (const charge of [0, 0.5, 1, 2.9, 3, 5, 6, 8]) {
  const cue = mix.driftBoostCue(label === '' ? null : label, charge);
  out(`\t{ TEXT("${label}"), ${num(charge)}, ${cue ? cue.level : 0}, ${num(cue ? cue.gain : 0)} },`);
}
out('};');

const target = join(here, '..', '..', 'Source', 'MovecadeKart', 'Private', 'Audio', 'Tests', 'KartAudioGolden.inl');
writeFileSync(target, lines.join('\n') + '\n');
console.log(`wrote ${target} (${lines.length} lines)`);
