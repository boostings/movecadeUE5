def box_glass_material():
    """The item box shell: translucent gold glass with bright fresnel edges and a slow rainbow shimmer band."""
    mat = new_material("M_ItemBoxGlass")
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("two_sided", True)
    mat.set_editor_property("used_with_instanced_static_meshes", True)
    color = vector(mat, "Color", (1.0, 0.6, 0.0, 1.0), -900, -200)
    edge = vector(mat, "EdgeColor", (1.0, 0.85, 0.35, 1.0), -900, 0)
    time = expr(mat, unreal.MaterialExpressionTime, -900, 200)
    wpos = expr(mat, unreal.MaterialExpressionWorldPosition, -900, 300)
    uv = expr(mat, unreal.MaterialExpressionTextureCoordinate, -900, 400)
    code_e = """
float3 n = normalize(Parameters.WorldNormal);
float3 v = normalize(Parameters.CameraVector);
float f = 1.0 - saturate(abs(dot(n, v)));
float2 p = abs(UV * 2.0 - 1.0);
float frame = smoothstep(0.80, 0.96, max(p.x, p.y));
float s = (WP.z * 0.01 + WP.x * 0.004 + WP.y * 0.004) * 0.5 - T * 0.35;
float band = pow(saturate(1.0 - abs(frac(s) - 0.5) * 6.0), 3.0);
float3 rainbow = saturate(abs(frac(s * 0.5 + f * 0.4 + float3(0.0, 2.0 / 3.0, 1.0 / 3.0)) * 6.0 - 3.0) - 1.0);
return Color * (0.35 + 0.5 * band) + rainbow * band * 0.6 + Edge * (pow(f, 2.2) * 2.2 + frame * 3.0);
"""
    e = custom(mat, -450, -100, code_e, ["Color", "Edge", "T", "WP", "UV"], out=F3, desc="Glass")
    for node, pin in ((color, "Color"), (edge, "Edge"), (time, "T"), (wpos, "WP"), (uv, "UV")):
        link(node, "", e, pin)
    code_o = """
float3 n = normalize(Parameters.WorldNormal);
float3 v = normalize(Parameters.CameraVector);
float f = 1.0 - saturate(abs(dot(n, v)));
float2 p = abs(UV * 2.0 - 1.0);
float frame = smoothstep(0.80, 0.96, max(p.x, p.y));
return saturate(0.22 + 0.55 * f + frame * 0.6);
"""
    o = custom(mat, -450, 200, code_o, ["UV"], desc="GlassOpacity")
    link(uv, "", o, "UV")
    to_prop(e, "", MP.MP_EMISSIVE_COLOR)
    to_prop(o, "", MP.MP_OPACITY)
    finish(mat)


