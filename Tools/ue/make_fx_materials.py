SCREEN = r"""
float2 uv = UV;
float aspect = max(1e-3, Size.x / max(1.0, Size.y));
float3 c = Scene.rgb;

// Prism (RaceUI.tsx starRainbow): a 45 deg rainbow wash at 0.15, shifting, and a soft rainbow frame with sparkles.
if (Prism > 0.0)
{
    float h = frac((uv.x * aspect + uv.y) * 0.25 - T * 0.5);
    float3 rainbow = saturate(abs(frac(h + float3(0.0, 2.0 / 3.0, 1.0 / 3.0)) * 6.0 - 3.0) - 1.0);
    c = lerp(c, rainbow, 0.12 * Prism);
    float2 px = uv * Size;
    float edge = min(min(px.x, Size.x - px.x), min(px.y, Size.y - px.y)) / max(1.0, Size.y);
    float frameA = 1.0 - smoothstep(0.0, 0.022, edge);
    c = lerp(c, rainbow * 1.2, frameA * 0.75 * Prism);
}

// Hit flash (kartFxBus flash: peak * (1 - t)^2, colour per profile).
c = lerp(c, HitColor.rgb, saturate(Hit));

// Lightning: a cold white flash that strobes twice, with an electric blue rim.
if (Zap > 0.0)
{
    float r = length((uv - 0.5) * float2(aspect, 1.0));
    float3 cold = float3(0.82, 0.92, 1.0);
    c = lerp(c, cold, saturate(Zap) * 0.85);
    c += float3(0.25, 0.45, 1.0) * smoothstep(0.35, 0.9, r) * Zap * 0.8;
}

// Explosion flash (RaceUI.tsx explosionFlash): radial #ffc864@.95 -> #ff6400@.8 at 30% -> clear at 70%,
// scale 0.5 -> 1.2 (30%) -> 1, opacity 1 -> 0 over 0.5 s.
if (FlashT >= 0.0 && FlashT < 1.0)
{
    float t = FlashT;
    float s = t < 0.3 ? lerp(0.5, 1.2, 1.0 - pow(1.0 - t / 0.3, 2.0)) : lerp(1.2, 1.0, (t - 0.3) / 0.7);
    float o = t < 0.3 ? 1.0 : 1.0 - (1.0 - pow(1.0 - (t - 0.3) / 0.7, 2.0));
    float r = length((uv - 0.5) * float2(aspect, 1.0)) / (0.5 * sqrt(aspect * aspect + 1.0)) / s;
    float4 a = float4(1.0, 0.784, 0.392, 0.95);
    float4 b = float4(1.0, 0.392, 0.0, 0.8);
    float4 g = r < 0.3 ? lerp(a, b, r / 0.3) : float4(b.rgb, lerp(b.a, 0.0, saturate((r - 0.3) / 0.4)));
    c = lerp(c, g.rgb, g.a * o);
}

// Ink (RaceUI.tsx inkSplatter): the web's five elliptical blots, given splattered edges, droplets and drips
// that run down while the ink is up. 0.1 s splat-in from 20 px above; fades over its last 0.4 s.
if (InkAge >= 0.0)
{
    float inA = saturate(InkAge / 0.1);
    float slide = (1.0 - saturate(InkAge / 0.1)) * (20.0 / max(1.0, Size.y));
    float outA = saturate(InkLeft / 0.4);
    float2 q = float2(uv.x, uv.y + slide);
    float4 blobs[5] = { float4(0.30, 0.20, 0.80, 0.60), float4(0.70, 0.30, 0.70, 0.50), float4(0.50, 0.70, 0.60, 0.70),
                        float4(0.20, 0.60, 0.50, 0.40), float4(0.80, 0.80, 0.40, 0.50) };
    float stops[5] = { 0.60, 0.55, 0.50, 0.45, 0.40 };
    float alphas[5] = { 0.94, 0.9, 0.86, 0.82, 0.78 };
    float clear = 1.0;
    float sheen = 0.0;
    for (int i = 0; i < 5; i++)
    {
        float2 d = (q - blobs[i].xy) / blobs[i].zw;
        float ang = atan2(d.y, d.x);
        float wob = 1.0 + 0.10 * sin(ang * 7.0 + i * 1.7) + 0.06 * sin(ang * 13.0 + i * 3.1) + 0.04 * sin(ang * 23.0 + i);
        float rr = length(d) / (stops[i] * 0.62 * wob);
        float body = 1.0 - smoothstep(0.86, 1.0, rr);
        float a = alphas[i] * body;
        // Droplets flung around each blot.
        for (int k = 0; k < 4; k++)
        {
            float da = i * 2.1 + k * 1.57 + 0.4;
            float dr = stops[i] * 0.62 * (1.25 + 0.25 * frac(sin(i * 7.1 + k * 3.3) * 91.7));
            float2 dc = blobs[i].xy + float2(cos(da), sin(da)) * dr * blobs[i].zw;
            float rad = 0.012 + 0.012 * frac(sin(i * 4.7 + k * 8.9) * 53.1);
            float drop = 1.0 - smoothstep(rad * 0.75, rad, length((q - dc) * float2(aspect, 1.0)));
            a = max(a, alphas[i] * drop);
        }
        // Drips: a few streaks below each blot, growing with time.
        for (int k2 = 0; k2 < 3; k2++)
        {
            float fx = blobs[i].x + (k2 - 1) * blobs[i].z * 0.16 + 0.02 * sin(i * 5.0 + k2 * 2.3);
            float w = (0.006 + 0.004 * frac(sin(i * 12.9 + k2 * 78.2) * 437.5));
            float top = blobs[i].y + blobs[i].w * stops[i] * 0.45;
            float len = (0.04 + 0.10 * frac(sin(i * 3.7 + k2 * 9.1) * 913.3)) * saturate(InkAge / 3.0) + 0.02;
            float inX = 1.0 - smoothstep(w * 0.6, w, abs(q.x - fx));
            float inY = step(top - 0.02, q.y) * (1.0 - smoothstep(top + len - 0.01, top + len, q.y));
            float tip = 1.0 - smoothstep(w * 1.4, w * 1.9, length(float2((q.x - fx) * aspect, q.y - top - len) / float2(aspect, 1.0)));
            a = max(a, alphas[i] * max(inX * inY, tip));
        }
        // Glossy highlight crescent near each blot's upper left.
        float2 hl = (q - blobs[i].xy) / blobs[i].zw + float2(0.12, 0.12) * stops[i];
        sheen += (1.0 - smoothstep(0.0, 0.08, abs(length(hl) / (stops[i] * 0.42) - 0.75))) * step(hl.x + hl.y, -0.02) * body * 0.35;
        clear *= 1.0 - a;
    }
    float inkA = (1.0 - clear) * inA * outA;
    float3 ink = float3(0.03, 0.018, 0.06) + saturate(sheen) * float3(0.45, 0.42, 0.6);
    c = lerp(c, ink, inkA);
}
return c;
"""


def screen_material():
    """Per-viewport post-process for the item screen effects (RaceUI.tsx overlays, kartFxBus hit flash, lightning)."""
    mat = new_material("M_PP_KartScreen")
    mat.set_editor_property("material_domain", unreal.MaterialDomain.MD_POST_PROCESS)
    mat.set_editor_property("blendable_location", unreal.BlendableLocation.BL_SCENE_COLOR_AFTER_TONEMAPPING)
    scene = expr(mat, unreal.MaterialExpressionSceneTexture, -900, -300)
    scene.set_editor_property("scene_texture_id", unreal.SceneTextureId.PPI_POST_PROCESS_INPUT0)
    pos = expr(mat, unreal.MaterialExpressionScreenPosition, -900, -100)
    size = expr(mat, unreal.MaterialExpressionViewSize, -900, 0)
    time = expr(mat, unreal.MaterialExpressionTime, -900, 100)
    params = {
        "Prism": scalar(mat, "Prism", 0.0, -900, 200),
        "Hit": scalar(mat, "Hit", 0.0, -900, 300),
        "HitColor": vector(mat, "HitColor", (1.0, 0.95, 0.86, 1.0), -900, 400),
        "Zap": scalar(mat, "Zap", 0.0, -900, 450),
        "FlashT": scalar(mat, "FlashT", -1.0, -900, 500),
        "InkAge": scalar(mat, "InkAge", -1.0, -900, 600),
        "InkLeft": scalar(mat, "InkLeft", 0.0, -900, 700),
    }
    node = custom(mat, -400, 0, SCREEN, ["Scene", "UV", "Size", "T"] + list(params.keys()), out=F3, desc="KartScreen")
    link(scene, "Color", node, "Scene")
    link(pos, "ViewportUV", node, "UV")
    link(size, "", node, "Size")
    link(time, "", node, "T")
    for name, p in params.items():
        link(p, "", node, name)
    to_prop(node, "", MP.MP_EMISSIVE_COLOR)
    finish(mat)


