def skid_material(noise):
    """Tyre marks: translucent dark road quads (UKartFxComponent's instanced segments). Custom data 0 is the time
    the segment was laid and "Now" the kart's clock; it fades out over 4 s. Soft along the edges, streaked by noise."""
    mat = new_material("M_FX_SkidMark")
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("used_with_instanced_static_meshes", True)
    mat.set_editor_property("translucency_pass", unreal.MaterialTranslucencyPass.MTP_BEFORE_DOF)
    born = expr(mat, unreal.MaterialExpressionPerInstanceCustomData, -900, 200, data_index=0, const_default_value=-100.0)
    time = scalar(mat, "Now", 0.0, -900, 300)
    uv = expr(mat, unreal.MaterialExpressionTextureCoordinate, -900, 50)
    wpos = expr(mat, unreal.MaterialExpressionWorldPosition, -900, 400)
    nuv = custom(mat, -650, 350, "return float2(WP.x * 0.006 + WP.y * 0.006, WP.y * 0.02 - WP.x * 0.02);", ["WP"], out=F2, desc="StreakUV")
    link(wpos, "", nuv, "WP")
    n = sample(mat, noise, -450, 350, nuv)
    code = """
float across = abs(UV.y * 2.0 - 1.0);
float edge = 1.0 - smoothstep(0.5, 1.0, across);
float streaks = lerp(0.45, 1.0, N);
float age = T - Born;
float life = saturate(age * 20.0) * (1.0 - smoothstep(2.5, 4.0, age));
return saturate(0.6 * edge * streaks * life);
"""
    op = custom(mat, -250, 100, code, ["UV", "N", "T", "Born"], desc="Skid")
    link(uv, "", op, "UV")
    link(n, "R", op, "N")
    link(time, "", op, "T")
    link(born, "", op, "Born")
    col = expr(mat, unreal.MaterialExpressionConstant3Vector, -250, -100, constant=unreal.LinearColor(0.018, 0.016, 0.02, 1.0))
    to_prop(col, "", MP.MP_EMISSIVE_COLOR)
    to_prop(op, "", MP.MP_OPACITY)
    finish(mat)


