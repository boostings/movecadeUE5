def glow_material():
    """Additive fresnel shell for glows (shell/bomb glow spheres, box halo, prism aura)."""
    mat = new_material("M_FX_Glow")
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_ADDITIVE)
    mat.set_editor_property("used_with_instanced_static_meshes", True)
    mat.set_editor_property("used_with_niagara_mesh_particles", True)
    color = vector(mat, "Color", (1.0, 0.6, 0.1, 1.0), -900, -200)
    inten = scalar(mat, "Intensity", 2.0, -900, 0)
    power = scalar(mat, "Power", 2.0, -900, 100)
    core = scalar(mat, "Core", 0.15, -900, 200)
    shimmer = scalar(mat, "Shimmer", 0.0, -900, 400)
    time = expr(mat, unreal.MaterialExpressionTime, -900, 500)
    wpos = expr(mat, unreal.MaterialExpressionWorldPosition, -900, 600)
    # Per-instance multiplier (ISM custom data 0), 1 when unused.
    inst = expr(mat, unreal.MaterialExpressionPerInstanceCustomData, -900, 300, data_index=0, const_default_value=1.0)
    code = """
float3 n = normalize(Parameters.WorldNormal);
float3 v = normalize(Parameters.CameraVector);
float f = 1.0 - saturate(abs(dot(n, v)));
float g = pow(f, Power) + Core;
// Optional shimmer: rainbow bands sweeping over the shell (the prism aura).
float band = frac(dot(WP, float3(0.004, 0.003, 0.006)) - T * 0.9 + f * 0.6);
float3 rainbow = saturate(abs(frac(band + float3(0.0, 2.0 / 3.0, 1.0 / 3.0)) * 6.0 - 3.0) - 1.0);
float3 c = lerp(Color, rainbow * 1.4, Shimmer);
float sparkle = Shimmer * pow(saturate(sin(dot(WP, float3(0.05, 0.07, 0.03)) + T * 7.0)), 24.0) * 3.0;
return c * Intensity * (g + sparkle * f) * Inst;
"""
    emis = custom(mat, -400, 0, code, ["Color", "Intensity", "Power", "Core", "Shimmer", "T", "WP", "Inst"], out=F3, desc="Glow")
    for node, pin in ((color, "Color"), (inten, "Intensity"), (power, "Power"), (core, "Core"), (shimmer, "Shimmer"), (time, "T"),
                      (wpos, "WP"), (inst, "Inst")):
        link(node, "", emis, pin)
    to_prop(emis, "", MP.MP_EMISSIVE_COLOR)
    finish(mat)


def fireball_material(noise):
    """Translucent explosion fireball lobes. ISM custom data 0 = life t in [0, 1]."""
    mat = new_material("M_FX_Fireball")
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("used_with_instanced_static_meshes", True)
    life = expr(mat, unreal.MaterialExpressionPerInstanceCustomData, -1000, 0, data_index=0, const_default_value=0.0)
    time = expr(mat, unreal.MaterialExpressionTime, -1000, 200)
    wpos = expr(mat, unreal.MaterialExpressionWorldPosition, -1000, 400)
    uvn = custom(mat, -750, 300, "float3 p = WP * 0.004; return float2(p.x + p.z * 0.7 + T * 0.35, p.y - p.z * 0.5 - T * 0.6);",
                 ["WP", "T"], out=F2, desc="NoiseUV")
    link(wpos, "", uvn, "WP")
    link(time, "", uvn, "T")
    n = sample(mat, noise, -500, 300, uvn)
    code = """
float t = saturate(Life);
float3 nrm = normalize(Parameters.WorldNormal);
float3 v = normalize(Parameters.CameraVector);
float facing = saturate(abs(dot(nrm, v)));
// Toon ramp: white-hot core -> yellow -> orange -> red -> soot as it cools.
float heat = saturate(facing * 1.25 - t * 1.05 + (Noise - 0.5) * 0.45 + 0.15);
float3 hot = float3(1.0, 0.97, 0.80);
float3 yel = float3(1.0, 0.78, 0.18);
float3 ora = float3(1.0, 0.36, 0.04);
float3 red = float3(0.75, 0.06, 0.02);
float3 soot = float3(0.10, 0.08, 0.075);
float3 c = red;
c = lerp(c, ora, smoothstep(0.18, 0.26, heat));
c = lerp(c, yel, smoothstep(0.45, 0.53, heat));
c = lerp(c, hot, smoothstep(0.72, 0.80, heat));
c = lerp(c, soot, smoothstep(0.55, 0.85, t));
float glow = lerp(7.0, 0.9, smoothstep(0.0, 0.6, t));
return c * glow;
"""
    col = custom(mat, -250, 0, code, ["Life", "Noise"], out=F3, desc="FireColor")
    link(life, "", col, "Life")
    link(n, "R", col, "Noise")
    op_code = """
float t = saturate(Life);
float3 nrm = normalize(Parameters.WorldNormal);
float3 v = normalize(Parameters.CameraVector);
float facing = saturate(abs(dot(nrm, v)));
// Crisp silhouette that breaks up into noisy holes as it burns out.
float body = smoothstep(0.10, 0.22, facing + (Noise - 0.5) * 0.25);
float erode = smoothstep(t * 1.15 - 0.05, t * 1.15 + 0.05, Noise * 0.8 + facing * 0.4);
return saturate(body * erode);
"""
    op = custom(mat, -250, 250, op_code, ["Life", "Noise"], desc="FireOpacity")
    link(life, "", op, "Life")
    link(n, "R", op, "Noise")
    to_prop(col, "", MP.MP_EMISSIVE_COLOR)
    to_prop(op, "", MP.MP_OPACITY)
    finish(mat)


