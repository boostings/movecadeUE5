"""Imports the FX textures and builds the FX and item materials under /Game/FX.

    python Tools\\fx\\make_fx_textures.py          (once, or after changing the textures)
    .\\Tools\\ue\\run.ps1 make_fx_materials.py

Textures come from Tools/fx/textures (all generated by Tools/fx/make_fx_textures.py). Every material is rebuilt from
scratch, so this script is the source of truth; C++ (Source/MovecadeKart/.../FX) sets the parameters.

Particle materials read the Niagara particle colour (rgb = colour with intensity baked in, a = alpha) and apply the
web ParticleField life curve themselves: alpha = smoothstep(0, 0.08, t) * (1 - t)^1.6 (rings ^1.2), with
t = Particles.NormalizedAge (ParticleRelativeTime). Shapes are procedural masks or the generated textures.
"""
import os

import unreal

quit_after = os.environ.get("KART_QUIT") == "1"
ROOT = "/Game/FX"
TEX = f"{ROOT}/Textures"
MAT = f"{ROOT}/Materials"
PROJECT = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())
SRC = os.path.join(PROJECT, "Tools", "fx", "textures")

mel = unreal.MaterialEditingLibrary
eal = unreal.EditorAssetLibrary
tools = unreal.AssetToolsHelpers.get_asset_tools()
MP = unreal.MaterialProperty
F1, F2, F3 = (unreal.CustomMaterialOutputType.CMOT_FLOAT1, unreal.CustomMaterialOutputType.CMOT_FLOAT2,
              unreal.CustomMaterialOutputType.CMOT_FLOAT3)


def log(msg):
    unreal.log(f"make_fx_materials: {msg}")


# ---------------------------------------------------------------- textures

def import_texture(file_name, asset_name, srgb=True, gray=False):
    task = unreal.AssetImportTask()
    task.set_editor_property("filename", os.path.join(SRC, file_name))
    task.set_editor_property("destination_path", TEX)
    task.set_editor_property("destination_name", asset_name)
    task.set_editor_property("automated", True)
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("save", False)
    tools.import_asset_tasks([task])
    tex = unreal.load_asset(f"{TEX}/{asset_name}")
    if tex is None:
        raise RuntimeError(f"import failed: {file_name}")
    tex.set_editor_property("srgb", srgb)
    if gray:
        tex.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_GRAYSCALE)
    tex.set_editor_property("lod_group", unreal.TextureGroup.TEXTUREGROUP_EFFECTS)
    eal.save_loaded_asset(tex, only_if_is_dirty=False)
    return tex


# ---------------------------------------------------------------- material helpers

def new_material(name):
    path = f"{MAT}/{name}"
    if eal.does_asset_exist(path):
        eal.delete_asset(path)
    return tools.create_asset(name, MAT, unreal.Material, unreal.MaterialFactoryNew())


def expr(mat, cls, x, y, **props):
    node = mel.create_material_expression(mat, cls, x, y)
    for key, value in props.items():
        node.set_editor_property(key, value)
    return node


def custom(mat, x, y, code, inputs, out=F1, desc="Custom"):
    node = expr(mat, unreal.MaterialExpressionCustom, x, y)
    node.set_editor_property("code", code)
    node.set_editor_property("output_type", out)
    node.set_editor_property("description", desc)
    ins = []
    for name in inputs:
        ci = unreal.CustomInput()
        ci.set_editor_property("input_name", name)
        ins.append(ci)
    node.set_editor_property("inputs", ins)
    return node


def link(a, a_out, b, b_in):
    if not mel.connect_material_expressions(a, a_out, b, b_in):
        raise RuntimeError(f"connect failed {a.get_name()}.{a_out} -> {b.get_name()}.{b_in}")


def to_prop(a, a_out, prop):
    if not mel.connect_material_property(a, a_out, prop):
        raise RuntimeError(f"connect to {prop} failed")


def scalar(mat, name, value, x, y):
    return expr(mat, unreal.MaterialExpressionScalarParameter, x, y, parameter_name=name, default_value=value)


def vector(mat, name, value, x, y):
    return expr(mat, unreal.MaterialExpressionVectorParameter, x, y, parameter_name=name, default_value=unreal.LinearColor(*value))


def sample(mat, texture, x, y, uv_node=None, uv_out=""):
    s = expr(mat, unreal.MaterialExpressionTextureSample, x, y)
    s.set_editor_property("texture", texture)
    gray = texture.get_editor_property("compression_settings") == unreal.TextureCompressionSettings.TC_GRAYSCALE
    srgb = texture.get_editor_property("srgb")
    if gray:
        s.set_editor_property("sampler_type", unreal.MaterialSamplerType.SAMPLERTYPE_GRAYSCALE if srgb else unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_GRAYSCALE)
    elif not srgb:
        s.set_editor_property("sampler_type", unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
    if uv_node is not None:
        link(uv_node, uv_out, s, "UVs")
    return s


def finish(mat):
    mel.layout_material_expressions(mat)
    mel.recompile_material(mat)
    eal.save_loaded_asset(mat, only_if_is_dirty=False)
    log(f"saved {mat.get_path_name()}")


def sprite_material(name, blend, two_sided=True):
    mat = new_material(name)
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    mat.set_editor_property("blend_mode", blend)
    mat.set_editor_property("two_sided", two_sided)
    mat.set_editor_property("used_with_niagara_sprites", True)
    mat.set_editor_property("used_with_niagara_mesh_particles", True)
    return mat


LIFE = """
float t = saturate(Time);
float fadeIn = smoothstep(0.0, 0.08, t);
return fadeIn * pow(1.0 - t, Power);
"""

MASKS = {
    # ParticleField.tsx fragment shader shapes, UV in [0,1].
    "soft": "float2 p = UV * 2.0 - 1.0; float d = length(p); float m = 1.0 - smoothstep(0.15, 1.0, d); return m * m;",
    "spark": "float2 p = UV * 2.0 - 1.0; float c = 1.0 - smoothstep(0.0, 1.0, length(float2(p.x * 1.6, p.y))); return c * c;",
    "ring": "float2 p = UV * 2.0 - 1.0; float d = length(p); return smoothstep(0.62, 0.86, d) * (1.0 - smoothstep(0.9, 1.0, d));",
}


def additive_particle(name, mask_kind=None, texture=None, life_power=1.6):
    """Additive sprite: emissive = ParticleColor.rgb * a * mask * life."""
    mat = sprite_material(name, unreal.BlendMode.BLEND_ADDITIVE)
    color = expr(mat, unreal.MaterialExpressionParticleColor, -900, -200)
    age = expr(mat, unreal.MaterialExpressionParticleRelativeTime, -900, 200)
    uv = expr(mat, unreal.MaterialExpressionTextureCoordinate, -900, 0)
    life = custom(mat, -600, 200, LIFE.replace("Power", f"{life_power:.3f}"), ["Time"], desc="Life")
    link(age, "", life, "Time")
    if texture is not None:
        shape = sample(mat, texture, -600, 0, uv)
        shape_out = "R"
    else:
        shape = custom(mat, -600, 0, MASKS[mask_kind], ["UV"], desc=mask_kind)
        link(uv, "", shape, "UV")
        shape_out = ""
    emis = custom(mat, -300, 0, "return Color * saturate(A * Shape * Life);", ["Color", "A", "Shape", "Life"], out=F3, desc="Emissive")
    link(color, "RGB", emis, "Color")
    link(color, "A", emis, "A")
    link(shape, shape_out, emis, "Shape")
    link(life, "", emis, "Life")
    to_prop(emis, "", MP.MP_EMISSIVE_COLOR)
    finish(mat)


PUFF = """
// A cartoon smoke puff: a lumpy disc with fake sphere lighting from above, eroding away with age.
float2 p = UV * 2.0 - 1.0;
float r = length(p);
float t = saturate(Age);
float lumps = N1 - 0.5;
float edge = 0.80 + lumps * 0.34;
float body = 1.0 - smoothstep(edge - 0.05, edge + 0.03, r);
// Erosion: a noise threshold that sweeps up over the second half of the life, from the rim inward.
float erodeField = N2 * 0.75 + (1.0 - r) * 0.45;
float threshold = smoothstep(0.35, 1.0, t) * 1.05;
float keep = smoothstep(threshold - 0.04, threshold + 0.04, erodeField);
float fadeIn = smoothstep(0.0, 0.06, t);
return body * keep * fadeIn * A;
"""

PUFF_SHADE = """
float2 p = UV * 2.0 - 1.0;
float r2 = saturate(dot(p, p));
float3 n = normalize(float3(p.x, -p.y, sqrt(1.0 - r2) + 0.25));
float3 L = normalize(float3(-0.35, 0.75, 0.55));
float diff = saturate(dot(n, L));
// Two-tone toon ramp with a soft step, plus a little lift in the core.
float tone = lerp(0.62, 1.08, smoothstep(0.25, 0.6, diff)) + (N1 - 0.5) * 0.10;
return Color * tone;
"""


def puff_material(noise):
    """Translucent toon puff for smoke, dust and explosion fire. Lit by the scene (so it darkens in tunnels and
    shade), with a baked toon shade on top; whatever the particle colour has above 1 glows (fire)."""
    mat = sprite_material("M_FX_Puff", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_DEFAULT_LIT)
    mat.set_editor_property("translucency_lighting_mode", unreal.TranslucencyLightingMode.TLM_VOLUMETRIC_NON_DIRECTIONAL)
    color = expr(mat, unreal.MaterialExpressionParticleColor, -1100, -300)
    age = expr(mat, unreal.MaterialExpressionParticleRelativeTime, -1100, 300)
    uv = expr(mat, unreal.MaterialExpressionTextureCoordinate, -1100, 0)
    rnd = expr(mat, unreal.MaterialExpressionParticleRandom, -1100, 150)
    uv1 = custom(mat, -850, 0, "return UV * 0.55 + R * float2(7.13, 3.71);", ["UV", "R"], out=F2, desc="UV1")
    uv2 = custom(mat, -850, 150, "return UV * 1.1 + R * float2(2.37, 5.19) + 0.31;", ["UV", "R"], out=F2, desc="UV2")
    for node in (uv1, uv2):
        link(uv, "", node, "UV")
        link(rnd, "", node, "R")
    n1 = sample(mat, noise, -600, 0, uv1)
    n2 = sample(mat, noise, -600, 150, uv2)
    alpha = custom(mat, -300, 150, PUFF, ["UV", "Age", "N1", "N2", "A"], desc="Puff")
    link(uv, "", alpha, "UV")
    link(age, "", alpha, "Age")
    link(n1, "R", alpha, "N1")
    link(n2, "R", alpha, "N2")
    link(color, "A", alpha, "A")
    shade = custom(mat, -300, -150, PUFF_SHADE, ["UV", "Color", "N1"], out=F3, desc="Shade")
    link(uv, "", shade, "UV")
    link(color, "RGB", shade, "Color")
    link(n1, "R", shade, "N1")
    base = custom(mat, -100, -250, "return saturate(C);", ["C"], out=F3, desc="Base")
    link(shade, "", base, "C")
    glow = custom(mat, -100, -100, "return max(C - 1.0, 0.0) * 0.8 + saturate(C) * 0.06;", ["C"], out=F3, desc="Glow")
    link(shade, "", glow, "C")
    to_prop(base, "", MP.MP_BASE_COLOR)
    to_prop(glow, "", MP.MP_EMISSIVE_COLOR)
    rough = expr(mat, unreal.MaterialExpressionConstant, -100, 50, r=1.0)
    to_prop(rough, "", MP.MP_ROUGHNESS)
    to_prop(alpha, "", MP.MP_OPACITY)
    finish(mat)


